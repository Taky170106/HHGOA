"""LangGraph investigation graph (Phase 4).

State machine (see AGENTS.md):

    START -> TRIAGE -> INVESTIGATE -> RETRIEVE -> ASSESS -> XAI
          -> CHECK_UNCERTAINTY -> [REQUEST_EVIDENCE -> REINVESTIGATE]
          -> GENERATE_ACTIONS -> COUNTERFACTUAL -> POLICY -> RECOMMEND -> END

Design rules enforced here:
  * graph evidence is authoritative — every number the nodes report is read
    from a live TigerGraph query or from the deterministic builder, never
    generated by the LLM;
  * every node appends a real trace entry (tool, HTTP status, latency);
  * the only branch in the graph is evidence sufficiency, and the
    request-evidence loop is bounded to one round by construction.
"""
